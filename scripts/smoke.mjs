import {connect,localConfig} from './connection.mjs';
const connection=await connect();
const health=await connection.api('/api/health');
const rules=await connection.api('/api/rules');
const tasks=await connection.api('/api/evaluations?latestPerSite=true');
const page=await fetch(connection.origin+'/');const html=await page.text();
const assets=[...html.matchAll(/(?:src|href)="(\/assets\/[^\"]+)"/g)].map(match=>match[1]);
for(const path of assets)if(!(await fetch(connection.origin+path)).ok)throw new Error('静态资源无法加载');
const unauthorized=await fetch(connection.origin+'/api/settings');
if(unauthorized.status!==401)throw new Error('匿名管理接口必须返回 401');
if(!assets.length || !page.ok)throw new Error('页面入口无效');
const env=localConfig();
const login=await fetch(connection.origin+'/api/login',{method:'POST',headers:{'Content-Type':'application/json',Origin:connection.origin},body:JSON.stringify({username:env.KOOBOO_USERNAME,password:env.KOOBOO_PASSWORD})});
const loginBody=await login.json();
const cookies=login.headers.getSetCookie().map(value=>value.split(';')[0]).join('; ');
if(!login.ok || !loginBody.ok || !cookies)throw new Error('平台登录失败或未设置 Cookie');
const session=await fetch(connection.origin+'/api/session',{headers:{Cookie:cookies,Origin:connection.origin}});
const settings=await fetch(connection.origin+'/api/settings',{headers:{Cookie:cookies,Origin:connection.origin}});
if(!session.ok || !settings.ok)throw new Error('Cookie 登录会话未保持');
const logout=await fetch(connection.origin+'/api/logout',{method:'POST',headers:{Cookie:cookies,Origin:connection.origin}});
if(!logout.ok || !(await logout.json()).ok)throw new Error('退出登录失败');
const expired=logout.headers.getSetCookie().filter(value=>/max-age=0(?:;|$)/i.test(value) || /expires=/i.test(value) && new Date(/expires=([^;]+)/i.exec(value)[1]).getTime()<=Date.now()).map(value=>value.slice(0,value.indexOf('=')));
const remaining=cookies.split('; ').filter(value=>!expired.includes(value.slice(0,value.indexOf('=')))).join('; ');
if(remaining===cookies)throw new Error('退出登录未清除登录 Cookie');
const afterLogout=await fetch(connection.origin+'/api/session',{headers:{Cookie:remaining,Origin:connection.origin}});
if(afterLogout.status!==401)throw new Error('退出后仍可访问登录会话');
console.log(JSON.stringify({health,rules:rules.items.length,evaluations:tasks.total,entry:page.status,assets:assets.length,anonymousSettings:unauthorized.status,login:login.status,cookieSession:session.status,cookieSettings:settings.status,logout:logout.status,afterLogout:afterLogout.status}));
