import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createDecipheriv, createHash } from 'node:crypto';
import { connect } from './connection.mjs';
const source=resolve(process.argv[2] || '../ai_site_evaluator/.data');
const db=new DatabaseSync(resolve(source,'database.sqlite'),{readOnly:true});
// This project currently has no historical jobs. Refuse to silently discard later data.
for(const table of ['evaluations','rule_drafts'])if(Number(db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get().n))throw new Error(`来源 ${table} 非空，需要先实现历史数据搬迁；本次没有写入目标`);
const rules=db.prepare('SELECT version,hash FROM rule_versions').all();db.close();
const packed=readFileSync(resolve(source,'settings.enc'));
const decipher=createDecipheriv('aes-256-gcm',readFileSync(resolve(source,'master.key')),packed.subarray(0,12));decipher.setAuthTag(packed.subarray(12,28));
const value=JSON.parse(Buffer.concat([decipher.update(packed.subarray(28)),decipher.final()]).toString());
const connection=await connect();
const targetRules=await connection.api('/api/rules');
if(rules.some(rule=>!targetRules.items.some(target=>target.version===rule.version && target.hash===rule.hash)))throw new Error('来源包含不同的规则版本，需要迁移规则后再导入配置；本次没有写入目标');
const migrationId=createHash('sha256').update(packed).digest('hex');
const result=await connection.api('/api/migrations/node-v1',{method:'POST',body:JSON.stringify({migrationId,settings:value.settings,credentials:value.credentials})});
const settings=await connection.api('/api/settings');
if(settings.credentials.ingestToken!==value.credentials.ingestToken || settings.credentials.readToken!==value.credentials.readToken)throw new Error('令牌迁移校验失败');
console.log(JSON.stringify({ok:result.ok,duplicate:result.duplicate,modelConfigured:!!(settings.model.endpoint && settings.model.name),environmentCount:settings.environments.length,tokensPreserved:true,historicalEvaluations:0}));
